// Keep a single context instance across HMR reloads of this module, otherwise
// hot updates create a new context and consumers throw "must be used within I18nProvider".
const I18nContext =
  globalThis.__ASCEND_I18N_CONTEXT__ ||
  (globalThis.__ASCEND_I18N_CONTEXT__ = createContext(null));

export function I18nProvider({ children }) {
  // English-only site: language and direction are fixed.
  const lang = "en";
  const t = translations.en;

  useEffect(() => {
    document.documentElement.lang = "en";
    document.documentElement.dir = "ltr";
  }, []);

  const format = useCallback((str, vars) => {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`));
  }, []);

  const value = { lang, t, dir: "ltr", format, tr: (key, vars) => format(t[key], vars) };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}