// Keep a single context instance across HMR reloads of this module, otherwise
// hot updates create a new context and consumers throw "must be used within I18nProvider".
const I18nContext =
  globalThis.__ASCEND_I18N_CONTEXT__ ||
  (globalThis.__ASCEND_I18N_CONTEXT__ = createContext(null));
const STORAGE_KEY = "ascend_lang";

export function I18nProvider({ children }) {
  // SSR renders the default language; the stored preference is read after
  // hydration to avoid a server/client markup mismatch.
  const [lang, setLang] = useState("ar");
  const [hydrated, setHydrated] = useState(false);
  const t = translations[lang];

  useEffect(() => {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && stored !== lang) setLang(stored);
    setHydrated(true);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  useEffect(() => {
    if (!hydrated) return;
    localStorage.setItem(STORAGE_KEY, lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = t.dir;
  }, [lang, t.dir, hydrated]);

  const toggleLang = useCallback(() => setLang((l) => (l === "en" ? "ar" : "en")), []);
  const format = useCallback((str, vars) => {
    if (!vars) return str;
    return str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : `{${k}}`));
  }, []);

  const value = { lang, setLang, toggleLang, t, dir: t.dir, format, tr: (key, vars) => format(t[key], vars) };
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}